const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('electronAPI', {
  getHardwareInfo: () => ipcRenderer.invoke('get-hardware-info'),
  chooseGameFolder: () => ipcRenderer.invoke('choose-game-folder'),
  getLauncherSettings: () => ipcRenderer.invoke('get-launcher-settings'),
  saveLauncherSettings: (settings) => ipcRenderer.invoke('save-launcher-settings', settings),
  windowMinimize: () => ipcRenderer.invoke('window-minimize'),
  windowMaximize: () => ipcRenderer.invoke('window-maximize'),
  windowClose: () => ipcRenderer.invoke('window-close'),
  launchMinecraft: (args) => ipcRenderer.invoke('launch-minecraft', args),
  installLoader: (args) => ipcRenderer.invoke('install-loader', args),
  scanInstalledVersions: (args) => ipcRenderer.invoke('scan-installed-versions', args),
  deleteVersion: (args) => ipcRenderer.invoke('delete-version', args),
  fetchMojangVersions: () => ipcRenderer.invoke('fetch-mojang-versions'),
  fetchModrinth: (args) => ipcRenderer.invoke('fetch-modrinth', args),
  downloadMod: (args) => ipcRenderer.invoke('download-mod', args),
  installCustomModpack: (args) => ipcRenderer.invoke('install-custom-modpack', args),
  installModpack: (args) => ipcRenderer.invoke('install-modpack', args),
  selectAndImportModpack: (args) => ipcRenderer.invoke('select-and-import-modpack', args),
  importFolderModpack: (args) => ipcRenderer.invoke('import-folder-modpack', args),
  applySkin: (args) => ipcRenderer.invoke('apply-skin', args),
  getEditorStyles: () => ipcRenderer.invoke('get-editor-styles'),
  saveEditorStyles: (styles) => ipcRenderer.invoke('save-editor-styles', styles),
  getPendingDeepLink: () => ipcRenderer.invoke('get-pending-deep-link'),
  onAuthCallback: (callback) => ipcRenderer.on('auth-callback', (_event, url) => callback(url)),
});